"""Execute the emitted extension with mocked native calls, not a replacement game.

Checks real branch/data operands and combat scenarios. This cannot establish the
engine's hit-history semantics, damage formula, replication or native query cost.
Run against an export generated by validate_arrow_chain.py.
"""
import json
import math
import re
import struct
from pathlib import Path


def fnv(text):
    value = 2166136261
    for byte in text.encode():
        value = ((value ^ byte) * 16777619) & 0xffffffff
    return value


class Program:
    def __init__(self, resource, disassembly):
        self.p = resource
        self.code = resource['code']
        self.layout = resource['dataLayout']
        self.names = {e['dbgName']: i for i, e in enumerate(self.layout)}
        self.functions = {}
        for line in disassembly.splitlines():
            m = re.match(r'ecall (\d+) (\w+) # \((.*)\)', line)
            if m:
                params = re.findall(r'(in|cfg|out) (\w+): ([^,]+)', m[3])
                self.functions[fnv(m[2])] = (m[2], params)

    def validate_structure(self, shutdown_text):
        for line in shutdown_text.splitlines():
            match = re.match(r'ecall (\d+) (\w+) # \((.*)\)', line)
            if match:
                self.functions[fnv(match[2])] = (match[2], re.findall(r'(in|cfg|out) (\w+): ([^,]+)', match[3]))
        maximum = 0
        for code in (self.code, self.p['codeShutdown']):
            boundaries, pc = {}, 0
            while pc < len(code):
                op = code[pc]
                width = 3 if op in (18, 19) else 2 if op in (8, 9, 10, 11, 21, 22, 23, 24) else 1
                assert pc + width <= len(code)
                boundaries[pc] = width
                if op in (21, 22, 23, 24):
                    assert code[pc+1] >> 16 == 0xffff
                    assert (code[pc+1] & 0xffff) < len(self.layout)
                if op in (22, 24):
                    entry = self.layout[code[pc+1] & 0xffff]
                    # Verified against revision 1273043's native VM dispatch.
                    # A 4-byte struct is NOT automatically a loadable uint32.
                    assert entry['type']['value'] in (848563180, 2556031774, 3365180733,
                                                      3756319748, 3902764048), (
                        'native VM rejects GLoad/GStore type', pc, entry['dbgName'], entry['type']['value'])
                pc += width
            queue, seen = [(0, 0)], {}
            while queue:
                pc, height = queue.pop()
                assert pc in boundaries, ('invalid branch', pc)
                if pc in seen:
                    assert seen[pc] == height, ('stack mismatch at branch join', pc)
                    continue
                seen[pc] = height
                op, width = code[pc], boundaries[pc]
                pop, push = 0, 0
                if op in (1, 2, 3, 4, 5, 6, 7): pop, push = 2, 1
                elif op in (9, 10, 24, 27): pop = 1
                elif op in (11, 12, 13, 22, 25): push = 1
                elif op in (14, 15): pop, push = 1, 1
                elif op == 17: pop, push = 1, 2
                elif op == 19:
                    pop, push = len(self.functions[code[pc+2]][1]), 1
                else:
                    assert op in (8, 28, 29, 30), ('unhandled opcode', op)
                assert height >= pop, ('stack underflow', pc)
                height += push-pop
                maximum = max(maximum, height)
                assert maximum <= self.p['stackSize']
                if op in (8, 9, 10): queue.append((code[pc+1], height))
                if op not in (8, 30): queue.append((pc+width, height))
        return maximum

    def scenario(self, ammo=3133483038, blocked=False, kill_initial=False,
                 history=True, rng=0, positions=None, overrides=None, deferred=True,
                 block_targets=(), reject_targets=(), kill_targets=(), **options):
        vm = VM(self, ammo, positions or {10: 0, 11: 6, 12: 12, 13: 18, 99: 3},
                history, rng, deferred)
        vm.block_targets=set(block_targets);vm.reject_targets=set(reject_targets);vm.kill_targets=set(kill_targets)
        for key,value in options.items(): setattr(vm,key,value)
        if self.code[0]==8:
            vm.run(0,{2});vm.stack.pop() # Original first GetRoot operand restored by trampoline.
        for key, value in (overrides or {}).items():
            vm.set('ZatArrowChain::' + key, value)
        vm.run(self.code[89], {94})  # Actual pre-hit trampoline.
        assert not vm.stack
        if kill_initial:
            vm.positions.pop(10)
        vm.visited.add(10)  # Simulate vanilla direct hit before post-hit hook.
        if not blocked:
            vm.run(self.code[211], {191})
        assert not vm.stack
        assert not vm.queries, 'query leaked on normal termination'
        return vm

    def spell_scenario(self, enabled=True, positions=None, overrides=None, history=True,
                       kill_initial=False, **options):
        vm=VM(self, 0, positions or {10: 0, 11: 6, 12: 12, 13: 18}, history, 0)
        vm.set('ZatSpellChain::enabled', int(enabled))
        for key,value in options.items(): setattr(vm,key,value)
        for key,value in (overrides or {}).items(): vm.set('ZatSpellChain::'+key,value)
        # The initial spell's original timing leaves one stack value to pop.
        vm.stack.append(250)
        vm.run(self.code[94], {98})
        assert vm.stack == [250]
        vm.stack.pop()
        vm.visited.add(10)
        if kill_initial: vm.positions.pop(10)
        vm.run(self.code[276], {143})
        assert not vm.stack and not vm.queries
        return vm


class VM:
    def __init__(self, program, ammo, positions, history, rng, deferred=True):
        self.program = program
        self.mem = bytearray(program.p["data"])
        self.positions = {e: ((float(p), 0., 0.) if isinstance(p, (int, float)) else tuple(p))
                          for e, p in positions.items()}
        self.history, self.rng = history, rng
        self.deferred = deferred
        self.pending_hits = set()
        self.resumes = 0
        self.stack, self.hits, self.visuals = [], [], []
        self.visited, self.queries = set(), {}
        self.block_targets = set()
        self.reject_targets = set()
        self.kill_targets = set()
        self.dead_targets = set()
        self.health = {}
        self.factions = {}
        self.reorder_queries = False
        self.missing_history = set()
        self.history_delay = 1
        self.pending_age = {}
        self.moves = {}
        self.tick_ms = 250
        self.now = 0
        self.hit_times = []
        self.destroyed = False
        self.hit_waves = []
        self.query_origins = []
        self.steps = 0
        self.namespace = 'ZatArrowChain' if 'Ammunition::value' in program.names else 'ZatSpellChain'
        if self.namespace == 'ZatSpellChain':
            self.set('Get_targetlock::targetId', 10)
            self.set('GetRoot::entityId', 1)
            self.set('Self1::entityId', 2)
            return
        self.set('Ammunition::value', ammo)
        if 'ZatArrowChain::managed_flight' in program.names:
            self.set('ZatArrowChain::managed_flight',int(ammo in (3133483038,2453015274,2369196415)))
        self.set('ForEach::otherEntity', 10)
        self.set('GetRoot::entityId', 1)
        self.set('CanBeBlocked::value', 1)

    def set(self, name, value):
        self.write(0xffff0000 + self.program.names[name], value)

    def read(self, ptr):
        if not ptr: return None
        entry = self.program.layout[ptr & 0xffff]
        data = self.mem[entry['offsetInBytes']:entry['offsetInBytes']+entry['size']]
        typ = entry['type']['value']
        if typ == 3902764048: return struct.unpack('<f', data)[0]
        if typ == 1025475970: return struct.unpack('<3f', data)
        if typ == 2492704965: return tuple(v/1024 for v in struct.unpack_from('<3q', data))
        if len(data) in (1, 2, 4, 8): return int.from_bytes(data, 'little')
        return bytes(data)

    def write(self, ptr, value):
        if not ptr: return
        entry = self.program.layout[ptr & 0xffff]
        typ, size, offset = entry['type']['value'], entry['size'], entry['offsetInBytes']
        if typ == 3902764048: data = struct.pack('<f', value)
        elif typ == 1025475970: data = struct.pack('<3f', *value)
        elif typ == 2492704965:
            # Model fixed-point positions; exact engine unit scale is irrelevant
            # to the bytecode tests. Views still share actual byte offsets.
            data = struct.pack('<3q', *(round(v*1024) for v in value)) + struct.pack('<8f',0,0,0,1,1,1,1,0)
        elif isinstance(value, int): data = (value & ((1 << (size*8))-1)).to_bytes(size, 'little')
        else: data = value
        assert len(data) == size
        self.mem[offset:offset+size] = data

    def run(self, pc, stops):
        c = self.program.code
        for _ in range(20000000):  # Test-harness watchdog only, not a shipped limit.
            if pc in stops:
                return
            self.steps += 1
            op = c[pc]; pc += 1
            if op in (8, 9, 10):
                target = c[pc]; pc += 1
                take = True if op == 8 else bool(self.stack.pop()) == (op == 9)
                if take:
                    pc = target
            elif op == 11:
                self.stack.append(c[pc]); pc += 1
            elif op in (12, 13):
                self.stack.append(op - 12)
            elif op in (14, 15):
                self.stack[-1] = (self.stack[-1] + (1 if op == 14 else -1)) & 0xffffffff
            elif op in (1, 2, 3, 5, 6, 7):
                b, a = self.stack.pop(), self.stack.pop()
                signed = lambda v: v - 0x100000000 if v & 0x80000000 else v
                if op == 7: result = int(signed(a) <= signed(b))
                elif op == 5: result = int(signed(a) < signed(b))
                elif op == 6: result = int(a == b)
                else: result = ({1: lambda: a+b, 2: lambda: a-b, 3: lambda: a*b}[op]()) & 0xffffffff
                self.stack.append(result)
            elif op == 17:
                self.stack.append(self.stack[-1])
            elif op == 22:
                entry = self.program.layout[c[pc] & 0xffff]
                assert entry['type']['value'] in (848563180, 2556031774, 3365180733,
                                                  3756319748, 3902764048), (
                    'native VM rejects GLoad type before damage', entry['dbgName'])
                value=self.read(c[pc])
                if entry["type"]["value"]==3756319748: value//=1000000
                self.stack.append(value); pc += 1
            elif op == 24:
                self.write(c[pc], self.stack.pop()); pc += 1
            elif op == 25:
                self.stack.append(self.now & 0xffffffff)
            elif op == 27:
                self.stack.pop()
            elif op == 28:
                # Native ApplyDamage enqueues a work item. Model the damage
                # processor updating history between VM executions. This is
                # still a model: real update order must be checked in combat.
                self.resumes += 1
                self.now += self.tick_ms
                if self.history:
                    for target in list(self.pending_hits):
                        self.pending_age[target]=self.pending_age.get(target,0)+1
                        if self.pending_age[target] >= self.history_delay:
                            if target not in self.missing_history: self.visited.add(target)
                            self.pending_hits.remove(target)
                else: self.pending_hits.clear()
                for target in self.kill_targets.intersection(t for t,_ in self.hits): self.positions.pop(target, None)
                self.positions.update(self.moves.get(self.resumes,{}))
            elif op == 30:
                return
            elif op == 29:
                self.destroyed = True
            elif op == 19:
                call_id, function = c[pc:pc+2]; pc += 2
                self.native(call_id, function)
            else:
                raise AssertionError(f'Unexpected opcode {op} at {pc - 1}')
        raise AssertionError('Extension did not terminate')

    def native(self, call_id, function):
        name, params = self.program.functions[function]
        args, refs = {}, {}
        for role in ('out', 'cfg', 'in'):
            for kind, key, typ in params:
                if kind == role:
                    ptr = self.stack.pop()
                    if ptr:
                        assert ptr >> 16 == 0xffff
                        entry = self.program.layout[ptr & 0xffff]
                        assert entry['offsetInBytes'] + entry['size'] <= len(self.program.p['data'])
                    refs[key] = ptr
                    args[key] = self.read(ptr)
        result = True
        if name == 'IsEnemy':
            a, b = args['entityAId'], args['entityBId']
            result = (a == 1 and b in self.positions and b != 99) or (b == 1 and a in self.positions and a != 99)
        elif name == 'GetTransform':
            position = self.positions[args['entityId']]
            self.write(refs['transform'], position)
            self.write(refs['position'], position)
        elif name == 'ForEachEntityWithFactionInRange':
            if call_id not in self.queries:
                origin, radius = args['transformInput'], args['range']
                self.query_origins.append(origin)
                items = [e for e, p in self.positions.items() if math.dist(p, origin) <= radius
                         and args['faction'] & (1 << self.factions.get(e,2))]
                if self.reorder_queries and len(self.query_origins)%2: items.reverse()
                self.queries[call_id] = items
            items = self.queries[call_id]
            index = args['index']
            result = index < len(items)
            if result:
                self.write(refs['entityId'], items[index])
                if 'transform' in refs: self.write(refs['transform'], self.positions[items[index]])
                self.write(refs['index'], index+1)
            else:
                self.queries.pop(call_id,None) # Native iterator destroys exhausted queries.
        elif name == 'FromTransform':
            self.write(refs['position'], args['transform'])  # Does NOT subtract referenceTransform.
        elif name == 'ApplyOffset':
            assert args['localOffset'] is None and args['worldOffset'] is None and args['orientationOffset'] is None
            self.write(refs['result'], args['transform'])
        elif name == 'SubValues':
            assert args['op'] == 1
            self.write(refs['result'], args['valueA'] - args['valueB'])
        elif name == 'GetLength':
            self.write(refs['result'], math.sqrt(sum(v*v for v in args['input'])))
        elif name == 'IsLess':
            assert args['op'] == 1
            result = args['valueA'] < args['valueB']
        elif name == 'DestroyFactionQuery':
            self.queries.pop(call_id, None)
        elif name == 'IsValidEntity':
            result = args['entityId'] in self.positions
        elif name == 'IsInState':
            assert args['state']==7
            result = args['entityId'] in self.dead_targets
        elif name == 'FetchOptionalAttribute':
            assert args['attributeRef']==bytes.fromhex('d4bd74f7a813624fa33e9630f601b285')
            hp = self.health.get(args['entityId'],100)
            result = hp is not None
            if result: self.write(refs['value'],hp)
        elif name == 'IsSameEntity':
            result = args['entityAId'] == args['entityBId']
        elif name == 'IsConsecutiveHit':
            result = args['entityId'] in self.visited
        elif name == 'GetConsecutiveHitCount':
            self.write(refs['count'], len(self.visited))
        elif name == 'RandomBranchNode':
            result = self.rng <= args['chance']
        elif name == 'SpawnEntity':
            assert args['addDespawnLink'] == 0
            if args['transform'] is not None:  # Ignore spell's native stamina child.
                pos = args['transform']
                pos = pos[0] if pos[1:] == (0., 0.) else pos
                self.visuals.append((pos, args['targetEntityId']))
        elif name == 'ApplyDamage':
            assert args['sourceId'] == (1 if self.namespace == 'ZatArrowChain' else 2)
            assert args['manaCost'] is None
            assert args['ignoreConsecutiveHits'] == 1
            assert args['canCrit'] in (None, 0)
            target = args['targetId']
            assert target not in self.dead_targets and self.health.get(target,100)>0
            assert target != 99 and target not in self.visited and target not in self.pending_hits
            self.write(refs['wasBlocked'], int(target in self.block_targets))
            if target in self.reject_targets:
                self.stack.append(0)
                return
            self.hits.append((target, args['attackMod']))
            self.hit_waves.append((self.resumes, target))
            self.hit_times.append((self.now,target))
            if self.history and not self.deferred:
                self.visited.add(target)
            elif self.history:
                self.pending_hits.add(target)
        else:
            raise AssertionError('Unmocked native function ' + name)
        self.stack.append(int(result))


def check(resource, disassembly):
    p = Program(resource, disassembly)
    results = []
    def record(name):
        results.append(name)
        print('PASS modeled bytecode:', name, flush=True)
    assert p.scenario(ammo=123).hits == []
    record('unrelated ammunition bypasses the extension')
    assert p.scenario(blocked=True).hits == []
    record('blocked direct hit never reaches post-hit extension')
    for ammo in (3133483038, 2453015274, 2369196415):
        v = p.scenario(ammo=ammo)
        assert [t for t, _ in v.hits] == [11, 12, 13]
        assert v.visuals == [(0, 11), (6, 12), (12, 13)]
    record('each tier propagates beyond the initial radius and excludes initial target/allies')
    assert p.scenario().resumes == 4
    assert len(p.scenario(deferred=False).hits) == 3
    record('deferred hit history is consumed after yielding; immediate-history model remains compatible')
    assert len(p.scenario(kill_initial=True).hits) == 3
    record('recorded origin and enemy eligibility survive an initial killing hit')
    assert len(p.scenario(positions={10: 0, 11: 2}).hits) == 1
    record('two enemies cannot ping-pong with native hit-history semantics')
    assert len(p.scenario(history=False).hits) == 1
    record('chain stops when secondary damage fails to enter native hit history')
    assert len(p.scenario(overrides={'eternal_20_radius': 2}).hits) == 0
    record('configured spread radius is consumed by the query')
    v = p.scenario(overrides={'eternal_20_damage': 9})
    assert [d for _, d in v.hits] == [9, 9, 9]
    record('independent secondary damage is used without clamping')
    return results


